//============================================================================
//  tanh.v -- output activation:  y = tanh(v) * 0.5 + 0.5
//----------------------------------------------------------------------------
//  The model ends with
//
//      out = torch.tanh(y) * 0.5 + 0.5        (out.2 has no norm, no ReLU)
//
//  so the very last thing the hardware does is squashing an unbounded value
//  into (0,1), which is then displayed as an 8-bit pixel.
//
//  Implementation: a 256-entry ROM per channel.
//    The pre-tanh value is carried as an int8 code q with scale s (v = q*s).
//    q has only 256 possible values, so tanh(q*s) has only 256 possible
//    results -- the whole activations+tone-map chain collapses to a table.
//    That makes it EXACT (no interpolation error) and costs no multiplier.
//
//    The table itself lives in tanh_lut.v, generated by gen_tanh_lut.py with
//    the per-channel scales baked in (each colour channel has its own range).
//
//  Latency: 1 cycle (registered output).
//============================================================================

`default_nettype none

module tanh #(
    parameter integer A4_MODE = 0,
    parameter integer C    = 3,         // channels (3 = RGB)
    parameter integer IW   = 8,         // input code width (int8)
    parameter integer OW   = 8          // output pixel width
)(
    input  wire                  clk,
    input  wire                  rst_n,

    input  wire                  in_valid,
    input  wire [C*IW-1:0]       in_px,

    output reg                   out_valid,
    output reg  [C*OW-1:0]       out_px
);

    wire [C*OW-1:0] lut_out;

    genvar g;
    generate
        for (g = 0; g < C; g = g + 1) begin : G_LUT
            // signed code -> index by adding 128
            wire [7:0] idx = in_px[g*IW +: IW] + 8'd128;
            tanh_lut #(.A4_MODE(A4_MODE), .CH_ID(g), .OW(OW)) u_lut (
                .idx(idx),
                .val(lut_out[g*OW +: OW])
            );
        end
    endgenerate

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            out_valid <= 1'b0;
            out_px    <= {C*OW{1'b0}};
        end else begin
            out_valid <= in_valid;
            if (in_valid)
                out_px <= lut_out;
        end
    end

endmodule

`default_nettype wire
